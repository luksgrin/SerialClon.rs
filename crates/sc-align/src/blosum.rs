fn index(aa: u8) -> usize {
    ORDER
        .iter()
        .position(|&x| x == aa.to_ascii_uppercase())
        .unwrap_or(22)
}

/// BLOSUM62 score of a pair; unknown letters score as `X`.
pub fn score(a: u8, b: u8) -> i32 {
    MATRIX[index(a)][index(b)] as i32
}

#[cfg(test)]
mod tests {
    #[test]
    fn symmetric_with_known_values() {
        assert_eq!(super::score(b'W', b'W'), 11);
        assert_eq!(super::score(b'I', b'L'), 2);
        assert_eq!(super::score(b'D', b'W'), -4);
        for a in super::ORDER {
            for b in super::ORDER {
                assert_eq!(super::score(*a, *b), super::score(*b, *a));
            }
        }
    }
}
